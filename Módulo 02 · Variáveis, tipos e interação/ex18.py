# Exercício 18 · Índices e fatias

# O índice começa em zero, como em C. A novidade é o índice negativo e o fatiamento.

# Exercício 18

palavra = "programacao"

print(palavra[0])                    # primeira letra
print(palavra[-1])                   # última letra (use índice negativo)
print(palavra[0:3])                  # as três primeiras letras
print(palavra[3:7])                  # da 4ª à 7ª letra (fatia [3:7])
print(len(palavra))                  # quantas letras tem a palavra