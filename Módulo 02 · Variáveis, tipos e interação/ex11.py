# Exercício 11 · Os operadores que mudam

# Com a = 7 e b = 2, imprima os cinco resultados. Antes de rodar, escreva num comentário o que o C devolveria em a / b.

# Exercício 11

a = 7
b = 2
                                 # Em C daria: 3   
print("a + b  =", a + b)         # Adição
print("a / b  =", a / b)         # Divisão comum
print("a // b =", a // b)        # Divisão inteira
print("a % b  =", a % b)         # Resto da divisão
print("a ** b =", a ** b)        # Potência